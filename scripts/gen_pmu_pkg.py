#!/usr/bin/env python3
"""Generate rtl/pmu/pmu_ev_pkg.sv (event ids, increment widths) from the trace-model's event list.

  gen_pmu_pkg.py [path/to/pmu_events.def]     default: ../trace-model/include/pmu_events.def (env PMU_EVENTS_DEF)

The .def file is the single source of the event list (trace-model include/pmu_events.def): the model's event vector,
this package and the analysis scripts all read it, so an event id means the same everywhere. mhpmevent holds id + 1
(0 = no event, the RISC-V convention).
"""
import os, re, sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
src = Path(sys.argv[1] if len(sys.argv) > 1 else os.environ.get("PMU_EVENTS_DEF", root.parent / "trace-model" / "include" / "pmu_events.def"))
evs = []
skipped = False
for line in src.read_text().splitlines():
    m = re.match(r'\s*PMU_EV\((\w+),\s*(\w+),\s*(\d+),\s*"(.*)"\)\s*(//.*)?$', line)
    if m:
        if m.group(5) and "model-only" in m.group(5):   # trailing "// model-only": counted by the trace-model only, no RTL lane
            skipped = True
            continue
        assert not skipped, f"{m.group(1)}: an event with an RTL lane follows a model-only one; ids would no longer match the model's list (tag only the tail of the table)"
        evs.append((m.group(1), m.group(2), int(m.group(3)), m.group(4)))
assert evs, f"no events in {src}"
inc_w = max(w for _, _, w, _ in evs)
out = [
    "// Ref: (generated) trace-model include/pmu_events.def -- GENERATED by scripts/gen_pmu_pkg.py, do not edit",
    "`default_nettype none",
    "/* verilator lint_off UNUSEDPARAM */  // constants package: not every event is used by every module",
    "",
    "package pmu_ev_pkg;",
    "",
    f"  localparam int PMU_NUM_EV = {len(evs)};",
    f"  localparam int PMU_INC_W  = {inc_w};  // widest per-cycle increment of any event",
    "",
    "  // event id = index on the event bus; mhpmevent[7:0] selects id + 1 (0 = no event)",
]
for i, (n, g, w, d) in enumerate(evs):
    line = f"  localparam int PMU_EV_{n} = {i};  // {g} +{w}b: {d.strip()}"
    out.append(line if len(line) <= 120 else line[:117] + "...")
widths = [str(w) for _, _, w, _ in evs]
out += ["", "  // increment width per event (bits actually driven; the rest of the bus lane is zero)",
        "  localparam int PMU_EV_W [PMU_NUM_EV] = '{"]
for i in range(0, len(widths), 20):
    out.append("    " + ", ".join(widths[i:i + 20]) + ("," if i + 20 < len(widths) else ""))
out += ["  };", "", "endpackage", "", "`default_nettype wire", ""]
(root / "rtl" / "pmu" / "pmu_ev_pkg.sv").write_text("\n".join(out))
(root / "tests" / "pmu" / "pmu_ev_widths.inc").write_text("// GENERATED by scripts/gen_pmu_pkg.py\n" + ", ".join(widths) + "\n")
print(f"{len(evs)} events -> rtl/pmu/pmu_ev_pkg.sv (inc width {inc_w})")
