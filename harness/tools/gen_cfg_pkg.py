#!/usr/bin/env python3
"""gen_cfg_pkg: emit rtl/common/ttg_cfg_pkg.sv from the reference simulator's config.h.

The C++ configuration is the single source of truth for every size/width in the RTL. The package is
generated (never edited): a throw-away C++ program includes config.h, evaluates every integral
`constexpr` constant (so clog2(), expressions and macros are resolved by the compiler) and prints it.

usage: gen_cfg_pkg.py <sim-src-dir> <out.sv> [-D<macro>=<val>]...
  <sim-src-dir>  root of the simulator tree (contains include/config.h); the standard include dirs of
                 the simulator are added automatically.
"""
import os
import re
import subprocess
import sys
import tempfile

DECL = re.compile(r'^\s*constexpr\s+(?:int|unsigned|uint32_t|uint64_t|int32_t|int64_t|size_t|long|bool)\s+'
                  r'([A-Z][A-Z0-9_]*)\s*=', re.M)

INC_DIRS = ['include', 'libs/include', 'back-end/include', 'back-end/Exu/include', 'back-end/Lsu/include',
            'back-end/tools/include', 'MemSubSystem/include', 'diff/include', 'function-model/include/api',
            'front-end', 'front-end/config', 'axi-interconnect-kit/include',
            'axi-interconnect-kit/axi_interconnect/include', 'axi-interconnect-kit/sim_ddr/include',
            'axi-interconnect-kit/mmio/include']


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    src, out = sys.argv[1], sys.argv[2]
    defs = [a for a in sys.argv[3:] if a.startswith('-D')]
    cfg = os.path.join(src, 'include', 'config.h')
    names = []
    for n in DECL.findall(open(cfg).read()):
        if n not in names:
            names.append(n)
    # front-end FIFO depths are #defines in front-end/config/frontend_feature_config.h (overridable with -D like the rest)
    fe = os.path.join(src, 'front-end', 'config', 'frontend_feature_config.h')
    fe_names = re.findall(r'^#define\s+((?:PTAB|INSTRUCTION_FIFO|FETCH_ADDR_FIFO|FRONT2BACK_FIFO)_SIZE)\s', open(fe).read(), re.M)
    names += [n for n in fe_names if n not in names]
    prog = ['#include "config.h"', '#include "frontend_feature_config.h"', '#include <cstdio>', 'int main(){']
    for n in names:
        prog.append(f'  std::printf("%s %llu\\n", "{n}", (unsigned long long)({n}));')
    prog.append('  return 0; }')
    with tempfile.TemporaryDirectory() as td:
        cpp = os.path.join(td, 'dump.cpp')
        exe = os.path.join(td, 'dump')
        open(cpp, 'w').write('\n'.join(prog))
        cmd = ['clang++', '-std=c++2a', '-w'] + defs + [f'-I{os.path.join(src, d)}' for d in INC_DIRS] + [cpp, '-o', exe]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            sys.exit('compile of config dump failed:\n' + r.stderr[-2000:])
        vals = subprocess.run([exe], capture_output=True, text=True, check=True).stdout.split('\n')
    lines = ['// Generated by harness/tools/gen_cfg_pkg.py from the reference simulator config.h -- do not edit.',
             '`default_nettype none', '/* verilator lint_off UNUSEDPARAM */', 'package ttg_cfg_pkg;']
    for v in vals:
        if not v:
            continue
        n, x = v.split()
        x = int(x)
        if x >= 1 << 31:
            lines.append(f"  localparam longint unsigned {n} = 64'd{x};")
        else:
            lines.append(f'  localparam int {n} = {x};')
    # RTL-only switch (not a trace-model constant): 1 = staged LSU (rtl/backend/lsu/lp_*.sv, docs/analysis/lsu-pipe.md), 0 = legacy LSU.
    # Default 1 (staged LSU); pass -DLSU_PIPE=0 to select the legacy LSU (trace-model counterpart: CFG_LSU_PIPE, default 1; env LSU_PIPE=0 there is the legacy LSU).
    lines.append('  localparam int LSU_PIPE = %d;' % (0 if '-DLSU_PIPE=0' in defs else 1))
    lines += ['endpackage', '`default_nettype wire', '']
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    open(out, 'w').write('\n'.join(lines))
    print(f'{out}: {len(vals) - 1} constants')


if __name__ == '__main__':
    main()
