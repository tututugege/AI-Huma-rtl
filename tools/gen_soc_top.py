#!/usr/bin/env python3
"""Generate rtl/core/soc_top/soc_top.sv: core_top + mem_top wired by port name (mem_top uses the core_top names, directions flipped).
Ports present on only one side become soc_top ports. `clk` of the core is `clk_cpu` (once per 16 fast ticks)."""
import re, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def hdr(f):
    t = open(os.path.join(ROOT, f)).read()
    m = re.search(r'module\s+(\w+).*?\(\s*(.*?)\n\);', t, re.S)
    ports = {}
    order = []
    for l in m.group(2).splitlines():
        l = re.sub(r'//.*', '', l).strip().rstrip(',')
        if not l:
            continue
        mm = re.match(r'(input|output)\s+logic\s*(.*?)\s*(\w+)\s*((?:\[[^\]]+\]\s*)*)$', l)
        d, ty, name, dims = mm.groups()
        ports[name] = (d, ty.strip(), dims.strip())
        order.append(name)
    return ports, order

core, corder = hdr('rtl/core/core_top/core_top.sv')
mem, morder = hdr('rtl/memsys/mem_top/mem_top.sv')
shared = [n for n in corder if n in mem and n not in ('clk', 'rst_n')]
for n in shared:
    assert core[n][0] != mem[n][0], f'{n}: same direction on both sides'
    assert core[n][1:] == mem[n][1:], f'{n}: type mismatch {core[n]} vs {mem[n]}'
top_ports = ['input  logic clk', 'input  logic clk_cpu', 'input  logic rst_n']
for n in corder:
    if n not in shared and n not in ('clk', 'rst_n'):
        d, ty, dims = core[n]
        top_ports.append(f'{"input " if d == "input" else "output"} logic {ty} {n} {dims}'.replace('  ', ' ').strip())
for n in morder:
    if n not in shared and n not in ('clk', 'rst_n'):
        d, ty, dims = mem[n]
        top_ports.append(f'{"input " if d == "input" else "output"} logic {ty} {n} {dims}'.replace('  ', ' ').strip())
nets = [f'  logic {core[n][1]} {n} {core[n][2]};'.replace('  ', ' ', 1).replace('logic  ', 'logic ') for n in shared]

out = ['// GENERATED by tools/gen_soc_top.py -- do not edit.',
       '// Ref: rv_simu_mmu_v2.cpp SimCpu::cycle (core + MemSubsystem + AXI subsystem);',
       '// DDR / MMIO / PhysMemory stay in the testbench.',
       '`default_nettype none', '',
       'module soc_top import ttg_cfg_pkg::*; import tlb_mmu_pkg::*; (']
out.append(',\n'.join('  ' + p for p in top_ports))
out.append(');')
out += nets
out.append('')
out.append('  core_top u_core (.clk(clk_cpu), .*);')
out.append('  mem_top  u_mem  (.clk, .*);')
out.append('endmodule')
out.append('`default_nettype wire')
open(os.path.join(ROOT, 'rtl/core/soc_top/soc_top.sv'), 'w').write('\n'.join(out) + '\n')
# tb-visible internal signals live in a Verilator config file, not in the RTL
vlt = ['// GENERATED by tools/gen_soc_top.py -- signals the SoC testbench reads (RTL carries no Verilator pragmas)', '`verilator_config']
vlt += [f'public_flat_rd -module "soc_top" -var "{n}"' for n in shared]
vlt += ['// the tick counter: the testbench jumps it over provably idle ticks', 'public_flat_rd -module "mem_top" -var "phase_q"', '// the reference counts a commit slot only when rob_bcast.interrupt is 0 (Ren.cpp: commit_num)', 'public_flat_rd -module "back_top" -var "rob_bcast_interrupt"', '// committed-store info for the platform device model', 'public_flat_rd -module "lsu_core" -var "st_fld_q"', '// function-model check: the destination register of each committed instruction and the physical register file', 'public_flat_rd -module "rob" -var "rob_commit_commit_entry_uop_dest_preg"', 'public_flat_rd -module "prf_regfile" -var "reg_file_q"', '// ... and the cause / privilege of an interrupt the core has just taken', 'public_flat_rd -module "csr" -var "regs"', 'public_flat_rd -module "csr" -var "privilege"']
open(os.path.join(ROOT, 'tb/soc/soc_public.vlt'), 'w').write('\n'.join(vlt) + '\n')
print('shared nets', len(shared), 'soc ports', len(top_ports))
