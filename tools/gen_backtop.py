def gen_exu(exu_ports):
    L = [HDR, '// Exu composite: exu_ctrl (Exu::comb_* without the functional units) + the 27 functional units (the CSR FU needs no',
         '// hardware, see below). Boundary = spec/exu.io (generated from spec/exu_ctrl.io). FU-side glue below is hand-written',
         '// text of the generator, see docs/modules/back_top.md for the contract with each FU.',
         '`default_nettype none', '', 'module exu', '  import ttg_cfg_pkg::*;', '  import exu_fu_pkg::*;',
         '  import exu_ctrl_pkg::*;', '(', '  input  logic clk,', '  input  logic rst_n,']
    pl = []
    for p in exu_ports:
        pl.append(f'  {"input " if p.dir == "in" else "output"} {sv_decl(p.width, p.dims, p.port)},')
    pl[-1] = pl[-1].rstrip(',')
    L += pl + [');']
    ctrl = []
    for p in exu_ports:
        ctrl.append(f'    .{p.port}({p.port}),')
    for pref in ('fu_', 'exu2fu_'):
        pass
    # FU side connections of exu_ctrl: all fu_* inputs and exu2fu_* outputs, in the exu_ctrl spec order
    _, ec_fields, _, _, _ = iogen.parse(os.path.join(ROOT, 'spec/exu_ctrl.io'))
    for f in ec_fields:
        if f.name.startswith(('fu_', 'exu2fu_')):
            ctrl.append(f'    .{f.name}({f.name}),')
    ctrl[-1] = ctrl[-1].rstrip(',')
    body = EXU_BODY.replace('@@CTRL_CONNS@@', '\n'.join(ctrl))
    L.append(body.rstrip('\n'))
    L += ['', 'endmodule', '', '`default_nettype wire']
    return '\n'.join(L) + '\n'


