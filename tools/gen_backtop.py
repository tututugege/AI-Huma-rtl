def wire_of(mod, port):
    for m, pat, rep in RENAMES:
        if m == mod and re.search(pat, port):
            return re.sub(pat, rep, port, count=1)
    return port


class P:
    """One module port as seen in a spec."""
    def __init__(self, inst, f):
        self.inst, self.f = inst, f
        self.port = f.name
        self.wire = wire_of(INST_MOD[inst], f.name)
        self.dir = f.dir
        self.width, self.dims = f.width, list(f.dims)
        self.when = wire_of(INST_MOD[inst], f.when) if f.when else None
        self.expr, self.wide = f.expr, f.wide


def load_exu_spec():
    """spec/exu.io = exu_ctrl.io without the FU side (fu_* / exu2fu_*): the composite's boundary equals Exu's BackTop wires."""
    src = open(os.path.join(ROOT, 'spec/exu_ctrl.io')).read().split('\n')
    out = ['# GENERATED by tools/gen_backtop.py from spec/exu_ctrl.io -- do not edit.',
           '# Exu composite (exu_ctrl + ALU/BRU/AGU/SDU/MUL/DIV/FPU functional units, rtl/backend/back_top/exu.sv).',
           '# Boundary = BackTop wires prf2exe, dec_bcast, rob_bcast, lsu2exe, csr2exe -> exe2prf, exe2iss, exe2csr, exe2lsu, exu2id, exu2rob.',
           '# Field set, `when` rules and consumer checks: docs/modules/exu_ctrl.md (the FU side is internal here).',
           'module exu', '']
    skip = re.compile(r'^(in|out)\s+(fu_|exu2fu_)')
    for ln in src:
        if ln.startswith('module '):
            continue
        if skip.match(ln):
            continue
        if ln.startswith('# ---- FU side') or ln.startswith('# ---- exu2fu') or ln.startswith('# FU index groups'):
            continue
        out.append(ln)
    return '\n'.join(out).rstrip('\n') + '\n'


def load_all():
    mods = {}
    exu_txt = load_exu_spec()
    for inst, mod, spec, _ in INSTANCES:
        if spec is None:
            continue
        path = os.path.join(ROOT, f'spec/{spec}.io')
        if inst == 'exu':
            tmp = os.path.join(ROOT, 'build/gen_backtop_exu.io')
            os.makedirs(os.path.dirname(tmp), exist_ok=True)
            open(tmp, 'w').write(exu_txt)
            path = tmp
        _, fields, _, _, _ = iogen.parse(path)
        mods[inst] = [P(inst, f) for f in fields]
    # glue
    g = []
    for n, (w, d) in GLUE_IN.items():
        g.append(P('glue', iogen.Field('in', n, w, d, None)))
    for n, (w, d) in GLUE_OUT.items():
        g.append(P('glue', iogen.Field('out', n, w, d, None)))
    mods['glue'] = g
    return mods, exu_txt


class Net:
    def __init__(self, wire, width, dims):
        self.wire, self.width, self.dims = wire, width, dims
        self.drivers = []      # (inst, port)
        self.readers = []      # (inst, port)
        self.consumer_expr = None
        self.is_const = False


def build_nets(mods):
    nets, issues = {}, []
    for inst, ports in mods.items():
        for p in ports:
            n = nets.setdefault(p.wire, Net(p.wire, p.width, p.dims))
            if (inst, p.port) in CONN_EXPR:      # explicit connection expression (e.g. one element of an array net)
                n.readers.append((inst, p.port))
                continue
            if (n.width, n.dims) != (p.width, p.dims):
                issues.append(('MISMATCH', p.wire, f'{inst}.{p.port} is {p.width}b{p.dims}, net is {n.width}b{n.dims} '
                               f'(first seen at {(n.drivers + n.readers)[0][0]})'))
            (n.drivers if p.dir == 'out' else n.readers).append((inst, p.port))
    for w in CONSTS:
        if w in nets:
            nets[w].is_const = True
    return nets, issues


def is_exported(wire):
    return wire not in NOT_EXPORTED and any(re.search(p, wire) for p in EXPORT)


def analyse(mods, nets, issues):
    boundary_in, boundary_out, unread = [], [], []
    for w, n in nets.items():
        if len(n.drivers) > 1:
            issues.append(('MULTI-DRIVER', w, ', '.join(f'{i}.{p}' for i, p in n.drivers)))
        if not n.drivers and not n.is_const:
            boundary_in.append(w)
        if n.is_const and n.drivers:
            issues.append(('CONST-ALSO-DRIVEN', w, ', '.join(f'{i}.{p}' for i, p in n.drivers)))
        if n.drivers and not n.readers and not is_exported(w):
            unread.append(w)
        if n.drivers and is_exported(w):
            boundary_out.append(w)
    return boundary_in, boundary_out, unread


def report(mods, nets, issues, bin_, bout, unread):
    ports = sum(len(v) for v in mods.values())
    print(f'instances: {len(mods)}  ports: {ports}  wires: {len(nets)}')
    drv = [n for n in nets.values() if n.drivers]
    by_inst_drv = sum(1 for n in drv if n.drivers[0][0] != 'glue')
    print(f'wires driven by a module: {by_inst_drv}, by glue: {len(drv) - by_inst_drv}, constants: {sum(n.is_const for n in nets.values())},'
          f' boundary inputs: {len(bin_)}, boundary outputs: {len(bout)}, unread outputs (dummies): {len(unread)}')
    print('\n== constant-driven wires (consumer needs it, no producer):')
    for w, r in CONSTS.items():
        print(f'  {w}  [{", ".join(i for i, _ in nets[w].readers)}]  {r}')
    print('\n== glue-driven wires:')
    for w in GLUE_OUT:
        print(f'  {w}  -> {", ".join(i for i, _ in nets[w].readers) or "(boundary)"}')
    print('\n== connection overrides (not name == name):')
    for (i, p), e in CONN_EXPR.items():
        print(f'  {i}.{p} <= {e}')
    for m, pat, rep in RENAMES:
        print(f'  rename {m}: {pat} -> {rep}')
    print('\n== issues:')
    if not issues:
        print('  none')
    for k, w, d in issues:
        print(f'  {k} {w}: {d}')
    print('\n== boundary inputs (no producer in the set):')
    for w in sorted(bin_):
        print(f'  {w} {nets[w].width}b{nets[w].dims}  <- {nets[w].readers[0][0]}')
    print('\n== outputs nobody reads (a consumer side would be needed, or they could be removed from the producer):')
    for w in sorted(unread):
        print(f'  {nets[w].drivers[0][0]}.{w} {nets[w].width}b{nets[w].dims}')


