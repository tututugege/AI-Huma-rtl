def sv_decl(width, dims, name, kind='logic'):
    w = '' if width == 1 else f'[{width - 1}:0] '
    d = ''.join(f'[{x}]' for x in dims)
    return f'{kind} {w}{name}{(" " + d) if d else ""}'


def group_of(wire, table, default):
    for pat, c in table:
        if re.search(pat, wire):
            return c
    return default


def select(mods, nets, sel):
    """Classify wires for a sub-set `sel` of instances. Returns dict with internal / top inputs / top outputs / dummies."""
    top_in, top_out, internal, dummies, consts = [], [], [], [], []
    for w, n in nets.items():
        rd = [i for i, _ in n.readers if i in sel]
        dr = [i for i, _ in n.drivers if i in sel]
        if not rd and not dr:
            continue
        if n.is_const:
            if rd:
                consts.append(w)
            continue
        if dr:
            outside_readers = [i for i, _ in n.readers if i not in sel]
            if outside_readers or is_exported(w):
                top_out.append(w)
            elif rd:
                internal.append(w)
            else:
                dummies.append(w)
        else:
            top_in.append(w)
    # `when` closure for exported outputs
    changed = True
    while changed:
        changed = False
        for w in list(top_out):
            pw = port_of(nets, w, 'out')
            if pw and pw.when and pw.when not in top_out:
                if pw.when in internal:
                    internal.remove(pw.when)
                    top_out.append(pw.when)
                    changed = True
                elif pw.when in dummies:
                    dummies.remove(pw.when)
                    top_out.append(pw.when)
                    changed = True
    return dict(top_in=top_in, top_out=top_out, internal=internal, dummies=dummies, consts=consts)


_PORTS = {}


def port_of(nets, wire, d):
    return _PORTS.get((wire, d))


def index_ports(mods):
    _PORTS.clear()
    for inst, ports in mods.items():
        for p in ports:
            _PORTS.setdefault((p.wire, p.dir), p)
            if p.dir == 'in':
                _PORTS.setdefault((p.wire, 'in*'), p)


def gen_top(name, mods, nets, sel, sel_order):
    S = select(mods, nets, sel)
    L = [HDR, f'// Instances: {", ".join(i for i in sel_order if i in sel)}.', '`default_nettype none', '',
         f'module {name} (', '  input  logic clk,', '  input  logic rst_n,']
    ports = []

    def emit_group(wires, table, direction, default):
        last = None
        for w in sorted(wires, key=lambda x: (min(range(len(table) + 1), key=lambda k: 0 if k == len(table) else
                                                    (0 if re.search(table[k][0], x) else 1) * 100 + k), x)):
            g = group_of(w, table, default)
            if g != last:
                ports.append(f'  // ---- {direction}: {g}')
                last = g
            n = nets[w]
            ports.append(f'  {"input " if direction == "in" else "output"} {sv_decl(n.width, n.dims, w)},')
    emit_group(S['top_in'], IN_GROUPS, 'in', 'other boundary inputs')
    emit_group(S['top_out'], OUT_GROUPS, 'out', 'other boundary outputs')
    ports[-1] = ports[-1].rstrip(',')
    L += ports
    L += [');', '']
    # internal nets, grouped by producer
    byprod = {}
    for w in S['internal']:
        byprod.setdefault(nets[w].drivers[0][0], []).append(w)
    for inst in sel_order:
        if inst in byprod:
            L.append(f'  // ---- nets driven by {inst}: {INST_DESC[inst]}')
            for w in sorted(byprod[inst]):
                L.append(f'  {sv_decl(nets[w].width, nets[w].dims, w)};')
            L.append('')
    if S['consts']:
        L.append('  // ---- constants (producer deleted a constant field / never writes it): see docs/modules/back_top.md')
        for w in sorted(S['consts']):
            n = nets[w]
            L.append(f'  {sv_decl(n.width, n.dims, w)};  // {CONSTS[w]}')
            zero = "'0" if not n.dims else "'{default: '0}"
            L.append(f'  assign {w} = {zero};')
        L.append('')
    if S['dummies']:
        L.append('  // ---- outputs nobody in this netlist reads (named so that no port is left empty)')
        L.append('  /* verilator lint_off UNUSEDSIGNAL */  // intentionally unread: listed in docs/modules/back_top.md')
        for w in sorted(S['dummies']):
            L.append(f'  {sv_decl(nets[w].width, nets[w].dims, "nc_" + w)};')
        L.append('  /* verilator lint_on UNUSEDSIGNAL */')
        L.append('')
    # instances
    for inst in sel_order:
        if inst not in sel:
            continue
        mod = INST_MOD[inst]
        L.append(f'  // ================= {inst}: {INST_DESC[inst]}')
        conns = []
        if inst != 'glue':
            conns.append(('.clk(clk)', ''))
            conns.append(('.rst_n(rst_n)', ''))
        elif False:
            pass
        srcs = {}
        for p in mods[inst]:
            n = nets[p.wire]
            if p.dir == 'in':
                if n.is_const:
                    src = 'tied 0'
                elif n.drivers:
                    src = n.drivers[0][0] if n.drivers[0][0] in sel else 'outside (top input)'
                else:
                    src = 'top input'
                expr = CONN_EXPR.get((inst, p.port), p.wire)
            else:
                expr = p.wire if (p.wire in S['top_out'] or p.wire in S['internal']) else 'nc_' + p.wire
                src = 'out'
            conns.append((f'.{p.port}({expr})', (p.dir, src)))
        # group: inputs by source, then outputs
        ins = [c for c in conns if c[1] and c[1][0] == 'in']
        outs = [c for c in conns if c[1] and c[1][0] == 'out']
        L.append(f'  {mod} u_{inst} (')
        L.append('    .clk(clk),') if inst != 'glue' else None
        L.append('    .rst_n(rst_n),') if inst != 'glue' else None
        lastsrc = None
        order = sorted(ins, key=lambda c: (c[1][1], c[0]))
        for c in order:
            if c[1][1] != lastsrc:
                L.append(f'    // inputs from {c[1][1]}')
                lastsrc = c[1][1]
            L.append(f'    {c[0]},')
        if outs:
            L.append('    // outputs')
        for c in outs:
            L.append(f'    {c[0]},')
        L[-1] = L[-1].rstrip(',')
        L.append('  );')
        L.append('')
    L += ['endmodule', '', '`default_nettype wire']
    return '\n'.join(L) + '\n', S


def gen_spec(name, mods, nets, sel, S, note):
    L = [f'# GENERATED by tools/gen_backtop.py -- do not edit.', f'# {note}',
         f'# Instances: {", ".join(sorted(sel))}. Inputs: reference wires driven into the RTL every cycle (expression of the consumer\'s',
         '# own spec); outputs: compared every cycle (expression and `when` of the producer\'s own spec).',
         f'module {name}', '']

    def line(direction, w, when, expr, n):
        dims = ''.join(f' [{d}]' for d in n.dims)
        wh = f' when {when}' if when else ''
        return f'{direction} {w} {n.width}{dims}{wh} @ {expr}'

    L.append('# ===== inputs')
    for w in sorted(S['top_in'], key=lambda x: (group_of(x, IN_GROUPS, 'z'), x)):
        n = nets[w]
        pc = port_of(nets, w, 'in*')
        # the consumer inside the selection
        cons = [p for p in sum(mods.values(), []) if p.wire == w and p.dir == 'in' and p.inst in sel]
        expr = cons[0].expr
        L.append(line('in ', w, None, expr, n))
    L.append('')
    L.append('# ===== outputs')
    for w in sorted(S['top_out'], key=lambda x: (group_of(x, OUT_GROUPS, 'z'), x)):
        n = nets[w]
        pw = port_of(nets, w, 'out')
        if pw.inst == 'glue':
            when, expr = GLUE_EXPORT.get(w, (None, None))
            assert expr, f'glue output {w} is exported but has no GLUE_EXPORT entry'
        else:
            when, expr = pw.when, pw.expr
        L.append(line('out', w, when, expr, n))
    return '\n'.join(L) + '\n'


