def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--report', action='store_true')
    ap.add_argument('--write', action='store_true')
    ap.add_argument('--full', action='store_true')
    ap.add_argument('--asm')
    ap.add_argument('--inst')
    ap.add_argument('--out')
    a = ap.parse_args()
    mods, exu_txt = load_all()
    index_ports(mods)
    nets, issues = build_nets(mods)
    bin_, bout, unread = analyse(mods, nets, issues)
    order = [i for i, _, _, _ in INSTANCES]
    if a.report or not (a.write or a.asm):
        report(mods, nets, issues, bin_, bout, unread)
        if not (a.write or a.asm):
            return
    hard = [x for x in issues if x[0] in ('MULTI-DRIVER', 'MISMATCH', 'CONST-ALSO-DRIVEN')]
    if hard:
        for k, w, d in hard:
            print(f'ERROR {k} {w}: {d}', file=sys.stderr)
        sys.exit(1)
    # wires that have a consumer but neither producer, const, nor boundary classification are plain boundary inputs: fine.
    if a.write:
        bt_dir = os.path.join(ROOT, 'rtl/backend/back_top')
        os.makedirs(bt_dir, exist_ok=True)
        open(os.path.join(ROOT, 'spec/exu.io'), 'w').write(exu_txt)
        exu_ports = mods['exu']
        open(os.path.join(bt_dir, 'exu.sv'), 'w').write(gen_exu(exu_ports))
        sel = set(order)
        sv, S = gen_top(TOP_NAME, mods, nets, sel, order)
        open(os.path.join(bt_dir, TOP_NAME + '.sv'), 'w').write(sv)
        open(os.path.join(ROOT, f'spec/{TOP_NAME}.io'), 'w').write(
            gen_spec(TOP_NAME, mods, nets, sel, S,
                     'Whole back end incl. RealLsu: boundary = front end + memory subsystem (SimCpu).' if FULL else
                     'Back end without RealLsu: everything between the front end / memory subsystem / LSU and the commit side.'))
        print(f'wrote exu.sv, {TOP_NAME}.sv ({sv.count(chr(10))} lines), spec/exu.io, spec/{TOP_NAME}.io '
              f'(inputs {len(S["top_in"])}, outputs {len(S["top_out"])})')
    if a.asm:
        sel = set(a.inst.split(','))
        bad = sel - set(order)
        if bad:
            sys.exit(f'unknown instances {bad}; known: {order}')
        out = a.out or os.path.join(ROOT, 'build/asm', a.asm)
        os.makedirs(out, exist_ok=True)
        sv, S = gen_top(a.asm, mods, nets, sel, order)
        open(os.path.join(out, a.asm + '.sv'), 'w').write(sv)
        # a sub-assembly spec can only be recorded if every field has an expression; inputs take the consumer's
        open(os.path.join(out, a.asm + '.io'), 'w').write(
            gen_spec(a.asm, mods, nets, sel, S, f'Sub-assembly {a.asm} of the back end (bisecting).'))
        print(f'wrote {out}/{a.asm}.sv, .io (inputs {len(S["top_in"])}, outputs {len(S["top_out"])})')


