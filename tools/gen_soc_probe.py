#!/usr/bin/env python3
"""Generate tb/soc/soc_probe.inc: reads every core_top boundary field (the spec/core_top.io layout) from the Verilated soc_top
into a trace-record-shaped byte buffer, so the closed-loop run can be compared field by field with a core_top trace recorded
from the reference simulator.  Needs build/lock_core_top/core_top_fields.h (iogen output) and rtl/core/soc_top/soc_top.sv."""
import re, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
hdr = open(os.path.join(ROOT, 'build/lock_core_top/core_top_fields.h')).read()
soc = open(os.path.join(ROOT, 'rtl/core/soc_top/soc_top.sv')).read()
nets = set(re.findall(r'^\s+logic\s+(?:\[[^\]]*\]\s*)?(\w+)', soc, re.M))
# 1-bit lane arrays declared as packed vectors (`logic [N-1:0] x`, no unpacked dims): read bit-wise
packed = set(re.findall(r'^\s*(?:input|output)?\s*logic\s+(?:\[[^\]]+\]\s*)+(\w+)\s*[,;)]?\s*(?://.*)?$', soc, re.M))
rows = re.findall(r'\{"(\w+)", (\d), (\d+), (\d), \{(\d+), (\d+), (\d+), (\d+)\}, (\d+), (\d+), (\d+), (-?\d+)\}', hdr)
in_b = re.search(r'kInBytes = (\d+)', hdr).group(1)
out_b = re.search(r'kOutBytes = (\d+)', hdr).group(1)
out = ['// GENERATED by tools/gen_soc_probe.py -- do not edit.',
       '// bit `i` of a packed 1-bit lane vector (CData/SData/IData/QData or VlWide)',
       'template <class T> static inline uint64_t ttg_getbit(const T &v, int i) { return (uint64_t(v) >> i) & 1; }',
       'template <size_t N> static inline uint64_t ttg_getbit(const VlWide<N> &v, int i) { return (v.at(i / 32) >> (i % 32)) & 1; }',
       'constexpr unsigned kInBytesProbe = ' + in_b + ';',
       'constexpr unsigned kOutBytesProbe = ' + out_b + ';',
       'struct ProbeField { const char *name; int is_out; int width; int nelem; int ebytes; int off; int when; };',
       'static const ProbeField kProbe[] = {']
for (name, is_out, width, nd, d0, d1, d2, d3, nelem, ebytes, off, when) in rows:
    out.append(f'  {{"{name}", {is_out}, {width}, {nelem}, {ebytes}, {off}, {when}}},')
out.append('};')
out.append('static void soc_probe(Vsoc_top *top, uint8_t *in, uint8_t *out) {')
out.append('  auto *R = top->rootp; (void)R;')
for (name, is_out, width, nd, d0, d1, d2, d3, nelem, ebytes, off, when) in rows:
    dims = [int(x) for x in (d0, d1, d2, d3)][:int(nd)]
    base = 'out' if is_out == '1' else 'in'
    ref = f'R->soc_top__DOT__{name}' if name in nets else f'top->{name}'
    if not dims:
        out.append(f'  ttg::put_elem({base} + {off}, {ebytes}, (uint64_t){ref});')
    elif name in packed and width == '1':
        lin = ' + '.join(f'i{k} * {int(__import__("math").prod(dims[k+1:]))}' for k in range(len(dims)))
        loops = ''.join(f'for (int i{k} = 0; i{k} < {dims[k]}; ++i{k}) ' for k in range(len(dims)))
        out.append(f'  {loops}ttg::put_elem({base} + {off} + ({lin}) * {ebytes}, {ebytes}, ttg_getbit({ref}, {lin}));')
    else:
        # row-major, nested indices
        idx = ''.join(f'[i{k}]' for k in range(len(dims)))
        lin = ' + '.join(f'i{k} * {int(__import__("math").prod(dims[k+1:]))}' for k in range(len(dims)))
        loops = ''.join(f'for (int i{k} = 0; i{k} < {dims[k]}; ++i{k}) ' for k in range(len(dims)))
        out.append(f'  {loops}ttg::put_elem({base} + {off} + ({lin}) * {ebytes}, {ebytes}, (uint64_t){ref}{idx});')
out.append('}')
# configuration widths the testbench needs to decode packed RTL structs (e.g. lsu_pkg::stq_fld_t), from the generated config package
cfg = open(os.path.join(ROOT, 'rtl/common/ttg_cfg_pkg.sv')).read()
for p in ('BR_MASK_WIDTH', 'ROB_IDX_WIDTH', 'PRF_IDX_WIDTH'):
    v = re.search(r'localparam int ' + p + r' = (\d+);', cfg).group(1)
    out.append(f'constexpr int kCfg_{p} = {v};')
open(os.path.join(ROOT, 'tb/soc/soc_probe.inc'), 'w').write('\n'.join(out) + '\n')
print(len(rows), 'fields')
