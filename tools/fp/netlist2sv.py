#!/usr/bin/env python3
"""Convert a reference-model gate netlist (fadd.h / fmul.h: `bool nK = ...;` AIG, `po[i] = ...;` outputs) to SystemVerilog.

usage: netlist2sv.py <netlist.h> <module_name> <out.sv> [--with-flags] [--no-prune]

Netlist grammar (checked strictly, anything else is an error):
    bool n0 = false;                  constant 0
    bool nK = pi[i];                  primary input alias; pi[0..31]=a, pi[32..63]=b, pi[64..66]=rm
    bool nK = [!]nA && [!]nB;         2-input AND node (operands must be defined earlier: topological order is asserted)
    po[i] = [!]nK;                    output i; po[0..31]=result, po[32..36]=fflags
Output module ports: a[31:0], b[31:0], rm[2:0] -> result[31:0] (and fflags[4:0] with --with-flags).
Without --with-flags only the 32 result bits are driven, and nodes that only feed fflags are dropped (cone-of-influence
pruning, --no-prune keeps everything). Node names are kept (nK) so the SV can be read against the C++ netlist.
"""
import re
import sys

PI_RE = re.compile(r'^\s*bool n(\d+) = pi\[(\d+)\];$')
AND_RE = re.compile(r'^\s*bool n(\d+) = (!?)n(\d+) && (!?)n(\d+);$')
CONST_RE = re.compile(r'^\s*bool n(\d+) = false;$')
PO_RE = re.compile(r'^\s*po\[(\d+)\] = (!?)n(\d+);$')
SKIP_RE = re.compile(r'^\s*(#ifndef|#define|#endif|extern const int|void \w+\(bool\* pi, bool\* po\) \{|\}\s*)')

PI_NAMES = {}
for i in range(32):
    PI_NAMES[i] = f'a[{i}]'
    PI_NAMES[32 + i] = f'b[{i}]'
for i in range(3):
    PI_NAMES[64 + i] = f'rm[{i}]'


def parse(path):
    consts, pis, ands, pos = {}, {}, {}, {}
    order = []
    with open(path) as f:
        for ln, line in enumerate(f, 1):
            line = line.rstrip('\n')
            if not line.strip() or SKIP_RE.match(line):
                continue
            if m := CONST_RE.match(line):
                consts[int(m[1])] = 0
                order.append(int(m[1]))
            elif m := PI_RE.match(line):
                pis[int(m[1])] = int(m[2])
                order.append(int(m[1]))
            elif m := AND_RE.match(line):
                k, na, a, nb, b = int(m[1]), m[2] == '!', int(m[3]), m[4] == '!', int(m[5])
                ands[k] = (na, a, nb, b)
                order.append(k)
            elif m := PO_RE.match(line):
                pos[int(m[1])] = (m[2] == '!', int(m[3]))
            else:
                sys.exit(f'{path}:{ln}: unrecognised line: {line!r}')
    defined = set()
    for k in order:
        if k in ands:
            _, a, _, b = ands[k]
            if a not in defined or b not in defined:
                sys.exit(f'node n{k} uses an operand defined later (netlist is not topologically ordered)')
        defined.add(k)
    return consts, pis, ands, pos, order


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    with_flags = '--with-flags' in sys.argv
    prune = '--no-prune' not in sys.argv
    if len(args) != 3:
        sys.exit(__doc__)
    src, mod, out = args
    consts, pis, ands, pos, order = parse(src)
    want = sorted(pos) if with_flags else [i for i in sorted(pos) if i < 32]
    if len(want) != (37 if with_flags else 32) or want[0] != 0:
        sys.exit('netlist does not have the expected 37 outputs')
    live = set()
    stack = [pos[i][1] for i in want]
    while stack:
        k = stack.pop()
        if k in live:
            continue
        live.add(k)
        if k in ands:
            stack += [ands[k][1], ands[k][3]]
    if not prune:
        live = set(order)
    nand = sum(1 for k in order if k in ands and k in live)
    src_name = src.split('/')[-1]
    o = []
    o.append(f'// Generated by tools/fp/netlist2sv.py from {src_name} ({"all outputs" if with_flags else "result bits only"}'
             f'{", pruned" if prune else ""}). Do not edit.')
    o.append(f'// Ref: back-end/Exu/include/{src_name}  gate netlist (pure combinational AIG, {nand} AND nodes)')
    o.append('// One `logic nK; assign nK = ...;` pair per live node of the C++ netlist, same numbering and topological order.')
    o.append('// Lint: every nK is declared and driven; the pair is kept on one line so the file stays diffable against the .h.')
    o.append('`default_nettype none')
    o.append('')
    o.append(f'module {mod} (')
    o.append('  input  logic [31:0] a,       // pi[0..31]')
    o.append('  input  logic [31:0] b,       // pi[32..63]')
    o.append('  input  logic [2:0]  rm,      // pi[64..66], 0..4 are the legal IEEE rounding modes of this netlist')
    if with_flags:
        o.append('  output logic [31:0] result,  // po[0..31]')
        o.append('  output logic [4:0]  fflags   // po[32..36] (differs from softfloat; the reference model never reads it)')
    else:
        o.append('  output logic [31:0] result   // po[0..31]')
    o.append(');')
    o.append('')

    def ref(k, neg):
        return ('~' if neg else '') + f'n{k}'

    for k in order:
        if k not in live:
            continue
        if k in consts:
            rhs = "1'b0"
        elif k in pis:
            rhs = PI_NAMES[pis[k]]
        else:
            na, a, nb, b = ands[k]
            rhs = f'{ref(a, na)} & {ref(b, nb)}'
        o.append(f'  logic n{k}; assign n{k} = {rhs};')
    o.append('')
    for i in want:
        neg, k = pos[i]
        tgt = f'result[{i}]' if i < 32 else f'fflags[{i - 32}]'
        o.append(f'  assign {tgt} = {ref(k, neg)};')
    o.append('')
    o.append('endmodule')
    o.append('')
    o.append('`default_nettype wire')
    with open(out, 'w') as f:
        f.write('\n'.join(o) + '\n')
    print(f'{out}: {len(o)} lines, {nand} AND nodes, {len(want)} outputs')


if __name__ == '__main__':
    main()
